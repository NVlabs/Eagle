def resolve_vflash_generation_kwargs(
    generate_kwargs,
    *,
    generation_config=None,
    default_eos_token_id=None,
) -> dict:
    """Resolve supported HF generation settings and reject semantic drift."""
    kwargs = dict(generate_kwargs)

    def take(name, default):
        if name in kwargs:
            return kwargs.pop(name)
        if generation_config is not None:
            value = getattr(generation_config, name, None)
            if value is not None:
                return value
        return default

    max_new_tokens = int(take("max_new_tokens", 20))
    do_sample = bool(take("do_sample", False))
    requested_temperature = float(take("temperature", 1.0))
    temperature = requested_temperature if do_sample else 0.0
    eos_token_id = take("eos_token_id", default_eos_token_id)
    top_p = float(take("top_p", 1.0))
    repetition_penalty = float(take("repetition_penalty", 1.0))
    use_cache = bool(take("use_cache", True))

    if max_new_tokens < 0:
        raise ValueError("max_new_tokens must be non-negative")
    if not math.isfinite(requested_temperature):
        raise ValueError("VFlash temperature must be finite")
    if do_sample and temperature <= 0:
        raise ValueError("VFlash sampling requires temperature > 0")
    if not math.isfinite(top_p) or not 0 < top_p <= 1:
        raise ValueError("VFlash top_p must be finite and in (0, 1]")
    if not math.isfinite(repetition_penalty) or repetition_penalty <= 0:
        raise ValueError("VFlash repetition_penalty must be finite and positive")
    if not use_cache:
        raise ValueError("VFlash generation requires use_cache=True")
    if abs(top_p - 1.0) > 1e-12:
        raise NotImplementedError(
            "VFlash generation does not silently ignore top_p; use top_p=1.0"
        )
    if abs(repetition_penalty - 1.0) > 1e-12:
        raise NotImplementedError(
            "VFlash generation does not silently ignore repetition_penalty; "
            "use repetition_penalty=1.0"
        )

    if generation_config is not None:
        unsupported_config = {
            "num_beams": (1,),
            "num_beam_groups": (1,),
            "num_return_sequences": (1,),
            "constraints": (None, []),
            "force_words_ids": (None, []),
        }
        invalid = [
            name for name, allowed in unsupported_config.items()
            if getattr(generation_config, name, None) not in allowed
        ]
        if do_sample:
            sampling_defaults = {
                "top_k": (None, 0),
                "typical_p": (None, 1.0),
                "min_p": (None, 0.0),
                "epsilon_cutoff": (None, 0.0),
                "eta_cutoff": (None, 0.0),
            }
            invalid.extend(
                name for name, allowed in sampling_defaults.items()
                if getattr(generation_config, name, None) not in allowed
            )
        if invalid:
            raise NotImplementedError(
                "Unsupported VFlash generation_config fields: "
                + ", ".join(sorted(set(invalid)))
            )
        if (
            "max_new_tokens" not in generate_kwargs
            and getattr(generation_config, "max_new_tokens", None) is None
        ):
            raise NotImplementedError(
                "VFlash generation_config requires max_new_tokens; max_length "
                "semantics are not supported"
            )

        # Fail closed for every other non-default HF control. These fields can
        # alter logits, stopping, output cardinality, or cache semantics and
        # therefore need explicit per-position integration with the verifier.
        from transformers import GenerationConfig

        baseline = GenerationConfig().to_dict()
        explicitly_handled = {
            "max_new_tokens", "do_sample", "temperature", "eos_token_id",
            "top_p", "top_k", "typical_p", "min_p", "epsilon_cutoff",
            "eta_cutoff", "repetition_penalty", "use_cache", "num_beams",
            "num_beam_groups", "num_return_sequences", "constraints",
            "force_words_ids",
        }
        inert_prompt_metadata = {
            "bos_token_id", "pad_token_id", "decoder_start_token_id",
            "transformers_version", "_from_model_config",
        }

        def normalized(value):
            try:
                return json.dumps(
                    value, sort_keys=True, separators=(",", ":"), default=str
                )
            except (TypeError, ValueError):
                return repr(value)

        active_unhandled = []
        for name, value in generation_config.to_dict().items():
            if name in explicitly_handled or name in inert_prompt_metadata:
                continue
            if normalized(value) != normalized(baseline.get(name)):
                active_unhandled.append(name)
        if active_unhandled:
            raise NotImplementedError(
                "Unsupported active VFlash generation_config fields: "
                + ", ".join(sorted(active_unhandled))
            )
    if kwargs:
        raise TypeError(
            "Unsupported VFlash generation arguments: "
            + ", ".join(sorted(kwargs))
        )

    stop_ids = (
        list(eos_token_id)
        if isinstance(eos_token_id, (list, tuple, set))
        else ([] if eos_token_id is None else [eos_token_id])
    )
    return {
        "max_new_tokens": max_new_tokens,
        "temperature": temperature,
        "stop_token_ids": [int(token_id) for token_id in stop_ids],
    }


def _sample(logits: torch.Tensor, temperature: float, banned_ids=()) -> torch.Tensor:
    logits = logits.clone()
    for token_id in banned_ids:
        if token_id is not None and 0 <= int(token_id) < logits.shape[-1]:
            logits[..., int(token_id)] = torch.finfo(logits.dtype).min
    if temperature < 1e-5:
        return logits.argmax(dim=-1)
    shape = logits.shape[:-1]
    probs = torch.softmax(logits.reshape(-1, logits.shape[-1]).float() / temperature, dim=-1)
    return torch.multinomial(probs, num_samples=1).reshape(shape)


def resolve_vflash_block_size(
    anchor_token_id: int,
    physical_config: Optional[Mapping],
    text_block_size: int = 16,
) -> tuple[int, Optional[Mapping]]:
    if int(text_block_size) != 16:
        raise ValueError(f"Ordinary-text VFlash block size must be 16, got {text_block_size}")
    spec = _atom_specs_by_start_id(physical_config).get(int(anchor_token_id))
    return (int(spec["block_size"]), spec) if spec is not None else (16, None)


def _first_atom_start_offset(
    token_ids: torch.Tensor,
    physical_config: Optional[Mapping],
    *,
    skip_anchor: bool = True,
) -> tuple[Optional[int], Optional[Mapping]]:
    """Find the first atom trigger in a would-be committed token sequence."""
    specs = _atom_specs_by_start_id(physical_config)
    first_offset = 1 if skip_anchor else 0
    for offset, token_id in enumerate(token_ids.reshape(-1).tolist()):
        if offset < first_offset:
            continue
        spec = specs.get(int(token_id))
        if spec is not None:
            return offset, spec
    return None, None


def parse_atomic_decoding_arguments(token_ids: Sequence[int], tokenizer) -> dict:
    """Read the most recent model-emitted atomic-decoding function call.

    Returns the complete ``arguments`` mapping; see
    :func:`~eaglevl.model.vflash.physical_atoms.parse_atomic_tool_arguments`.
    """
    if tokenizer is None:
        raise ValueError("atomic_decoding generation requires atomic_decoding_tokenizer")
    text = tokenizer.decode([int(value) for value in token_ids], skip_special_tokens=False)
    arguments = parse_atomic_tool_arguments(text)
    if arguments is None:
        raise ValueError("physical trajectory started before an atomic_decoding tool call")
    return arguments


def parse_atomic_decoding_block_size(token_ids: Sequence[int], tokenizer) -> int:
    """Read ``block_size`` from the most recent atomic-decoding function call."""
    return int(parse_atomic_decoding_arguments(token_ids, tokenizer)["block_size"])


def parse_atomic_decoding_call(
    token_ids: Sequence[int], tokenizer
) -> tuple[int, Optional[int]]:
    """Return the latest tool call's block size and optional primitive count."""
    arguments = parse_atomic_decoding_arguments(token_ids, tokenizer)
    count = arguments.get("count")
    if count is not None and (
        isinstance(count, bool) or not isinstance(count, int) or count < 1
    ):
        raise ValueError(
            f"atomic_decoding count must be a positive integer, got {count!r}"
        )
    return int(arguments["block_size"]), (None if count is None else int(count))


def _select_atomic_layout(
    *,
    block_size: int,
    count: Optional[int],
    only_offset: int,
    only_stride: int,
    joint_offset: int,
    joint_stride: int,
    first_name: str,
) -> bool:
    """Return True for the single-modality layout, False for the joint layout."""
    only = block_size > only_offset and (block_size - only_offset) % only_stride == 0
    joint = block_size > joint_offset and (block_size - joint_offset) % joint_stride == 0
    if count is not None:
        only = only and (block_size - only_offset) // only_stride == int(count)
        joint = joint and (block_size - joint_offset) // joint_stride == int(count)
    # Preserve the historical joint interpretation when a count-less block is
    # arithmetically compatible with both layouts.
    if joint:
        return False
    if only:
        return True
    raise ValueError(
        f"B{block_size}"
        + (f" with count {count}" if count is not None else "")
        + f" is incompatible with atomic layouts starting at {first_name}"
    )


def _atomic_layout_parts(
    anchor_id: int,
    block_size: int,
    physical_config: Mapping,
    count: Optional[int] = None,
):
    by_name = {
        str(spec["name"]): (int(start_id), spec)
        for start_id, spec in _atom_specs_by_start_id(physical_config).items()
    }
    first = _atom_specs_by_start_id(physical_config).get(int(anchor_id))
    first_name = None if first is None else str(first["name"])
    if first_name == "drive_3d_bev":
        numerator, denominator = block_size - 2, 2
        names = ("drive_3d_bev",)
    elif first_name == "drive_2d":
        only_2d = _select_atomic_layout(
            block_size=block_size,
            count=count,
            only_offset=2,
            only_stride=2,
            joint_offset=4,
            joint_stride=4,
            first_name=first_name,
        )
        if only_2d:
            numerator, denominator = block_size - 2, 2
            names = ("drive_2d",)
        else:
            numerator, denominator = block_size - 4, 4
            names = ("drive_2d", "drive_3d_bev")
    elif first_name == "robot_single_3d":
        numerator, denominator = block_size - 2, 3
        names = ("robot_single_3d",)
    elif first_name == "robot_single_2d":
        only_2d = _select_atomic_layout(
            block_size=block_size,
            count=count,
            only_offset=2,
            only_stride=2,
            joint_offset=4,
            joint_stride=5,
            first_name=first_name,
        )
        if only_2d:
            numerator, denominator = block_size - 2, 2
            names = ("robot_single_2d",)
        else:
            numerator, denominator = block_size - 4, 5
            names = ("robot_single_2d", "robot_single_3d")
    elif first_name == "robot_left_3d":
        numerator, denominator = block_size - 4, 6
        names = ("robot_left_3d", "robot_right_3d")
    elif first_name == "robot_left_2d":
        only_2d = _select_atomic_layout(
            block_size=block_size,
            count=count,
            only_offset=4,
            only_stride=4,
            joint_offset=8,
            joint_stride=10,
            first_name=first_name,
        )
        if only_2d:
            numerator, denominator = block_size - 4, 4
            names = ("robot_left_2d", "robot_right_2d")
        else:
            numerator, denominator = block_size - 8, 10
            names = (
                "robot_left_2d", "robot_left_3d",
                "robot_right_2d", "robot_right_3d",
            )
    elif first_name == "dense_3d":
        # One query point's F-frame 3D path: B = 3F + 2.
        numerator, denominator = block_size - 2, 3
        names = ("dense_3d",)
    elif first_name == "dense_2d":
        # One query point's 2D path followed by its 3D path: B = 5F + 4.
        numerator, denominator = block_size - 4, 5
        names = ("dense_2d", "dense_3d")
    else:
        raise ValueError(
            "atomic_decoding trajectory has an unsupported first physical atom: "
            f"{first_name!r}"
        )
    if numerator <= 0 or numerator % denominator:
        raise ValueError(
            f"B{block_size} is incompatible with atomic layout starting at {first_name}"
        )
    points = numerator // denominator
    parts = []
    for name in names:
        start_id, spec = by_name[name]
        payload_length = points * int(spec["dimensions"])
        parts.append((start_id, spec, payload_length))
    if sum(payload + 2 for _, _, payload in parts) != block_size:
        raise AssertionError("atomic layout formula produced the wrong block size")
    return parts


def validate_atomic_decoding_block(
    block_ids: Sequence[int], physical_config: Mapping, count: Optional[int] = None
) -> tuple[bool, str]:
    ids = [int(value) for value in block_ids]
    if not ids:
        return False, "empty block"
    try:
        parts = _atomic_layout_parts(ids[0], len(ids), physical_config, count=count)
    except ValueError as error:
        return False, str(error)
    numeric = {int(value) for value in physical_config["numeric_id_to_value"]}
    oof = int(physical_config["oof_token_id"])
    cursor = 0
    for part_index, (start_id, spec, payload_length) in enumerate(parts):
        if ids[cursor] != start_id:
            return False, f"part {part_index} has wrong start token"
        payload = ids[cursor + 1:cursor + 1 + payload_length]
        error = _atom_payload_error(
            payload, spec.get("allow_oof_pairs", False), numeric, oof
        )
        if error == "oof":
            return False, f"invalid <oof> pair in part {part_index}"
        if error == "numeric":
            return False, f"non-numeric payload in part {part_index}"
        if ids[cursor + payload_length + 1] != int(spec["end_id"]):
            return False, f"part {part_index} has wrong end token"
        cursor += payload_length + 2
    return (cursor == len(ids), "" if cursor == len(ids) else "trailing tokens")


def validate_publication(
    result_ids: Sequence[int], physical_config: Mapping, tokenizer
) -> int:
    """Validate mixed fixed and variable primitives before publishing output."""
    ids = [int(value) for value in result_ids]
    starts = _atom_specs_by_start_id(physical_config)
    end_ids = {int(spec["end_id"]) for spec in starts.values()}
    reserved = end_ids | {
        int(physical_config[key])
        for key in ("oof_token_id", "mask_token_id", "null_token_id")
        if physical_config.get(key) is not None
    }
    blocks = 0
    dense_seen = 0
    dense_expected = None
    index = 0
    while index < len(ids):
        spec = starts.get(ids[index])
        if spec is None:
            if ids[index] in reserved:
                raise RuntimeError("Refusing to publish an orphan physical token")
            index += 1
            continue
        name = str(spec["name"])
        if is_variable_trajectory_atom_name(name):
            arguments = parse_atomic_decoding_arguments(ids[:index], tokenizer)
            block_size = int(arguments["block_size"])
            count = arguments.get("count")
            count = None if count is None else int(count)
            if name == "drive_3d_bev":
                if count is not None and block_size != 3 * count + 2:
                    raise RuntimeError(
                        "XY-heading driving count does not match block_size"
                    )
                if count is None and block_size not in {18, 26, 62, 194}:
                    raise RuntimeError(
                        "Driving without count must use a registered native horizon"
                    )
            if name == "dense_3d":
                dense_seen += 1
                if count is not None:
                    if dense_expected is None:
                        dense_expected = count
                    elif dense_expected != count:
                        raise RuntimeError("Dense trajectory tool counts disagree")
            try:
                parts = _atomic_layout_parts(
                    ids[index], block_size, physical_config, count=count
                )
            except ValueError as error:
                raise RuntimeError(
                    "Refusing to publish an invalid trajectory layout: "
                    + str(error)
                ) from error
            block = ids[index:index + block_size]
            valid, reason = validate_atomic_decoding_block(
                block, physical_config, count=count
            )
            if not valid or index + block_size > len(ids):
                raise RuntimeError(
                    "Refusing to publish an invalid trajectory: " + reason
                )
            # Re-check with the count-aware layout when count is present.
            if sum(payload + 2 for _, _, payload in parts) != block_size:
                raise RuntimeError("Trajectory count does not match block_size")
        else:
            block_size = int(spec["block_size"])
            tail = ids[index + 1:index + block_size]
            valid, reason = validate_serialized_atom_tail(
                ids[index], tail, physical_config
            )
            if not valid or index + block_size > len(ids):
                raise RuntimeError(
                    "Refusing to publish an invalid fixed atom: " + reason
                )
        blocks += 1
        index += block_size
    if dense_expected is not None and dense_seen != dense_expected:
        raise RuntimeError(
            f"Dense trajectory tool count is {dense_expected}, published {dense_seen} atoms"
        )
    return blocks


def _atomic_tail_descriptors(parts):
    descriptors = []
    for part_index, (start_id, spec, payload_length) in enumerate(parts):
        if part_index:
            descriptors.append(("exact", start_id, None, None))
        descriptors.extend(
            ("payload", None, spec, payload_index)
            for payload_index in range(payload_length)
        )
        descriptors.append(("exact", int(spec["end_id"]), None, None))
    return descriptors


def _sample_atomic_tail_slot(
    logits, descriptor, prior_tail, physical_config, temperature
):
    kind, exact_id, spec, payload_index = descriptor
    if kind == "exact":
        allowed = {int(exact_id)}
    elif str(spec.get("name")) == "bbox_2d":
        current_payload = (
            list(prior_tail[-payload_index:]) if payload_index else []
        )
        return _sample_atom_slot(
            logits,
            spec,
            int(payload_index),
            current_payload,
            physical_config,
            temperature,
        )
    else:
        numeric = {int(value) for value in physical_config["numeric_id_to_value"]}
        if spec.get("allow_oof_pairs", False):
            oof = int(physical_config["oof_token_id"])
            if payload_index % 2 == 0:
                allowed = numeric | {oof}
            else:
                allowed = {oof} if prior_tail[-1] == oof else numeric
        else:
            allowed = numeric
    indices = torch.tensor(sorted(allowed), dtype=torch.long, device=logits.device)
    restricted = logits.index_select(-1, indices)
    local_id = _sample(restricted, temperature)
    return indices[local_id]


def _sample_atomic_tail(
    logits: torch.Tensor,
    parts,
    physical_config: Mapping,
    temperature: float,
) -> torch.LongTensor:
    """Sample a complete atomic trajectory under its slot-level wire schema.

    DFlash predicts all masked slots in parallel, but argmax must still be
    restricted by what each slot represents.  Coordinate slots admit numeric
    physical tokens only (plus a protocol-valid paired ``<oof>`` for 2D drive
    projections), while atom boundaries are forced to their exact structure
    token.  This prevents ordinary text or tool-call tokens from entering a
    trajectory proposal.
    """
    descriptors = _atomic_tail_descriptors(parts)
    if logits.ndim != 3 or logits.shape[0] != 1:
        raise ValueError("atomic trajectory proposal logits must have shape [1, tail, vocab]")
    if logits.shape[1] != len(descriptors):
        raise ValueError(
            f"atomic trajectory tail has {logits.shape[1]} logits for "
            f"{len(descriptors)} schema slots"
        )
    sampled = []
    for slot, descriptor in enumerate(descriptors):
        token = _sample_atomic_tail_slot(
            logits[:, slot, :],
            descriptor,
            sampled,
            physical_config,
            temperature,
        )
        sampled.append(int(token.item()))
    return torch.tensor(sampled, dtype=torch.long, device=logits.device).unsqueeze(0)


def _sample_atom_tail(
    logits: torch.Tensor,
    spec: Mapping,
    physical_config: Mapping,
    temperature: float,
) -> torch.LongTensor:
    """Sample one fixed physical atom with numeric/structure slot masks."""
    expected = int(spec["block_size"]) - 1
    if logits.ndim != 3 or logits.shape[:2] != (1, expected):
        raise ValueError(
            f"{spec.get('name')} proposal logits must have shape "
            f"[1, {expected}, vocab]"
        )
    sampled = []
    for slot in range(expected):
        token = _sample_atom_slot(
            logits[:, slot, :],
            spec,
            slot,
            sampled,
            physical_config,
            temperature,
        )
        sampled.append(int(token.item()))
    return torch.tensor(sampled, dtype=torch.long, device=logits.device).unsqueeze(0)


def _ordinary_banned_ids(
    mask_token_id: int, physical_config: Optional[Mapping]
) -> tuple[int, ...]:
    specs = _atom_specs_by_start_id(physical_config)
    banned = {int(mask_token_id)}
    banned.update(int(spec["end_id"]) for spec in specs.values())
    if physical_config and physical_config.get("oof_token_id") is not None:
        banned.add(int(physical_config["oof_token_id"]))
    if physical_config and physical_config.get("null_token_id") is not None:
        banned.add(int(physical_config["null_token_id"]))
    return tuple(sorted(banned))


def _allowed_atom_ids(
    spec: Mapping,
    slot: int,
    prior_tail: Sequence[int],
    physical_config: Mapping,
) -> set[int]:
    payload_length = int(spec["payload_length"])
    if slot == payload_length:
        return {int(spec["end_id"])}
    numeric_values = {
        int(token_id): int(value)
        for token_id, value in physical_config["numeric_id_to_value"].items()
    }
    numeric_ids = set(numeric_values)
    if spec.get("allow_oof_pairs", False):
        oof = int(physical_config["oof_token_id"])
        if slot % 2 == 0:
            return numeric_ids | {oof}
        return {oof} if prior_tail[-1] == oof else numeric_ids
    if spec.get("name") == "bbox_2d" and slot in (0, 1):
        maximum = max(numeric_values.values())
        return {
            token_id for token_id, value in numeric_values.items()
            if value < maximum
        }
    if spec.get("name") == "bbox_2d" and slot in (2, 3):
        lower_value = numeric_values[int(prior_tail[slot - 2])]
        return {
            token_id for token_id, value in numeric_values.items()
            if value > lower_value
        }
    return numeric_ids


def _sample_atom_slot(
    logits: torch.Tensor,
    spec: Mapping,
    slot: int,
    prior_tail: Sequence[int],
    physical_config: Mapping,
    temperature: float,
) -> torch.Tensor:
    allowed = _allowed_atom_ids(spec, slot, prior_tail, physical_config)
    if not allowed:
        raise RuntimeError(f"No legal token remains for {spec.get('name')} slot {slot}")
    indices = torch.tensor(sorted(allowed), dtype=torch.long, device=logits.device)
    restricted = logits.index_select(-1, indices)
    local_id = _sample(restricted, temperature)
    return indices[local_id]


def _contains_stop(output_ids: torch.Tensor, generated_start: int, stop_ids: set[int]) -> bool:
    if not stop_ids:
        return False
    generated = output_ids[0, generated_start:]
    return any(bool((generated == token_id).any()) for token_id in stop_ids)


@torch.inference_mode()
def dflash_generate(
    draft_model,
    target_language_model,
    input_ids: torch.LongTensor,
    inputs_embeds: torch.FloatTensor,
    attention_mask: Optional[torch.LongTensor],
    max_new_tokens: int,
    stop_token_ids: Optional[Sequence[int]] = None,
    temperature: float = 0.0,
    physical_atom_config: Optional[Mapping] = None,
    text_block_size: int = 16,
    verify_atoms: bool = False,
    return_stats: bool = False,
    atomic_decoding_tokenizer=None,
    draft_temperature: float = 0.0,
    bbox_hybrid: Optional[BBoxHybridConfig] = None,
    initial_prefix_token_ids: Optional[Sequence[int]] = None,
    publication_errors: str = "raise",
):
    """Generate for one unpadded prompt using separate target/draft KV caches.

    ``draft_temperature`` only affects the drafter's physical-atom proposals
    (0.0 = argmax). A positive value yields different committed trajectories
    per call, which is what a best-of-N evaluation of the drafter needs.

    ``bbox_hybrid`` routes the call to
    :func:`~eaglevl.model.vflash.bbox_hybrid.bbox_hybrid_generate`, which
    requires the query-derived ``initial_prefix_token_ids``.

    ``publication_errors`` selects what happens when the final publication
    check rejects the output. ``"raise"`` propagates the error;
    ``"return"`` returns the rejected output unchanged, with the error message
    in ``stats.publication_error``, and therefore requires ``return_stats``.
    """
    if input_ids.ndim != 2 or input_ids.shape[0] != 1:
        raise ValueError("VFlash generation currently requires batch size 1")
    if inputs_embeds.shape[:2] != input_ids.shape:
        raise ValueError("inputs_embeds and input_ids must have identical batch/sequence axes")
    if attention_mask is not None and not bool(attention_mask.bool().all()):
        raise ValueError("VFlash generation does not accept padded prompts; generate one sample at a time")
    if max_new_tokens < 0:
        raise ValueError("max_new_tokens must be non-negative")
    if max_new_tokens == 0:
        empty = input_ids[:, :0]
        if not return_stats:
            return empty
        return SimpleNamespace(
            output_ids=empty,
            num_input_tokens=input_ids.shape[1],
            num_output_tokens=0,
            time_to_first_token=0.0,
            time_per_output_token=0.0,
            acceptance_lengths=[],
            atom_fallbacks=0,
        )
    if int(text_block_size) != 16:
        raise ValueError("Ordinary-text VFlash uses fixed block size 16")
    draft_temperature = float(draft_temperature)
    if not math.isfinite(draft_temperature) or draft_temperature < 0.0:
        raise ValueError("draft_temperature must be finite and non-negative")
    if publication_errors not in PUBLICATION_ERROR_POLICIES:
        raise ValueError(
            f"publication_errors must be one of {PUBLICATION_ERROR_POLICIES}, "
            f"got {publication_errors!r}"
        )
    if bbox_hybrid is not None:
        if verify_atoms or temperature != 0 or draft_temperature != 0:
            raise ValueError("BBox hybrid decoding requires an unverified greedy drafter")
        if initial_prefix_token_ids is None:
            raise ValueError("BBox hybrid decoding requires the query-derived initial prefix")
        if publication_errors != "raise":
            raise ValueError("publication_errors='return' does not apply to bbox hybrid decoding")
        from .bbox_hybrid import bbox_hybrid_generate

        return bbox_hybrid_generate(
            draft_model=draft_model, target_language_model=target_language_model,
            input_ids=input_ids, inputs_embeds=inputs_embeds, attention_mask=attention_mask,
            max_new_tokens=max_new_tokens, stop_token_ids=stop_token_ids,
            physical_atom_config=physical_atom_config, config=bbox_hybrid,
            return_stats=return_stats, initial_prefix_token_ids=initial_prefix_token_ids,
        )
    if initial_prefix_token_ids is not None:
        raise ValueError("Initial prefix requires bbox hybrid decoding")
    if verify_atoms:
        raise ValueError(
            "VFlash commits physical atoms without target verification; "
            "verify_atoms=True is not supported"
        )
    if atomic_decoding_tokenizer is None:
        raise ValueError(
            "VFlash generation requires atomic_decoding_tokenizer"
        )
    if publication_errors == "return" and not return_stats:
        raise ValueError("publication_errors='return' requires return_stats=True")

    device = inputs_embeds.device
    prompt_length = input_ids.shape[1]
    max_atom_block = max(
        [int(spec["block_size"]) for spec in _atom_specs_by_start_id(physical_atom_config).values()]
        or [text_block_size]
    )
    capacity = prompt_length + max_new_tokens + max_atom_block + 1
    mask_token_id = int(
        getattr(draft_model, "mask_token_id", None)
        if getattr(draft_model, "mask_token_id", None) is not None
        else physical_atom_config["mask_token_id"]
    )
    output_ids = torch.full(
        (1, capacity), mask_token_id, dtype=torch.long, device=device
    )
    output_ids[:, :prompt_length] = input_ids
    all_position_ids = torch.arange(capacity, device=device).unsqueeze(0)
    target_cache = DynamicCache()
    draft_cache = DynamicCache()
    stop_ids = {int(token_id) for token_id in (stop_token_ids or [])}
    ordinary_banned_ids = _ordinary_banned_ids(mask_token_id, physical_atom_config)

    if return_stats and device.type == "cuda":
        torch.cuda.synchronize(device)
    prefill_started = time.perf_counter()
    target_output = target_language_model(
        inputs_embeds=inputs_embeds,
        attention_mask=attention_mask,
        position_ids=all_position_ids[:, :prompt_length],
        past_key_values=target_cache,
        use_cache=True,
        logits_to_keep=1,
        output_hidden_states=True,
        return_dict=True,
    )
    first_token = _sample(
        target_output.logits, temperature, ordinary_banned_ids
    )
    output_ids[:, prompt_length] = first_token.reshape(1)
    first_spec = _atom_specs_by_start_id(physical_atom_config).get(
        int(first_token.item())
    )
    # A trajectory's length comes from its tool call, so only fixed atoms can
    # be checked against the budget here.
    if (
        first_spec is not None
        and not is_variable_trajectory_atom_name(first_spec.get("name", ""))
        and max_new_tokens < int(first_spec["block_size"])
    ):
        raise ValueError(
            f"max_new_tokens truncates {first_spec['name']} atom: need "
            f"{first_spec['block_size']} tokens from its start, have {max_new_tokens}"
        )
    target_hidden = extract_context_feature(
        target_output.hidden_states, draft_model.target_layer_ids
    )
    full_target_hidden = target_hidden
    if return_stats and device.type == "cuda":
        torch.cuda.synchronize(device)
    time_to_first_token = time.perf_counter() - prefill_started

    start = prompt_length
    max_length = prompt_length + max_new_tokens
    acceptance_lengths = []
    atom_fallbacks = 0
    atom_fallback_reasons = []
    atom_fallback_details = []
    decode_started = time.perf_counter()

    while start < max_length - 1 and not _contains_stop(output_ids[:, :start + 1], prompt_length, stop_ids):
        anchor_id = int(output_ids[0, start])
        block_size, atom_spec = resolve_vflash_block_size(
            anchor_id, physical_atom_config, text_block_size
        )
        atomic_parts = None
        atomic_count = None
        block_atomic_mode = atom_spec is not None and is_variable_trajectory_atom_name(
            atom_spec.get("name", "")
        )
        if block_atomic_mode:
            block_size, atomic_count = parse_atomic_decoding_call(
                output_ids[0, prompt_length:start].tolist(),
                atomic_decoding_tokenizer,
            )
            atomic_parts = _atomic_layout_parts(
                anchor_id,
                block_size,
                physical_atom_config,
                count=atomic_count,
            )
        remaining_with_anchor = max_length - start
        if atom_spec is not None and remaining_with_anchor < block_size:
            raise ValueError(
                f"max_new_tokens truncates {atom_spec['name']} atom: need {block_size} "
                f"tokens from its start, have {remaining_with_anchor}"
            )
        block_size = min(block_size, remaining_with_anchor)

        block_ids = output_ids[:, start:start + block_size].clone()
        noise_embedding = target_language_model.get_input_embeddings()(block_ids)
        draft_positions = all_position_ids[
            :, draft_cache.get_seq_length():start + block_size
        ]
        draft_hidden = draft_model(
            target_hidden=target_hidden,
            noise_embedding=noise_embedding,
            position_ids=draft_positions,
            past_key_values=draft_cache,
            use_cache=True,
            is_causal=False,
        )
        draft_logits = target_language_model.lm_head(draft_hidden[:, 1:, :])
        if atom_spec is None:
            block_ids[:, 1:] = _sample(
                draft_logits, 0.0, ordinary_banned_ids
            )
        elif atomic_parts is not None:
            block_ids[:, 1:] = _sample_atomic_tail(
                draft_logits,
                atomic_parts,
                physical_atom_config,
                draft_temperature,
            )
        else:
            block_ids[:, 1:] = _sample_atom_tail(
                draft_logits,
                atom_spec,
                physical_atom_config,
                draft_temperature,
            )
        # Discard this round's noisy K/V while retaining injected target context.
        draft_cache.crop(start)

        verified = target_language_model(
            input_ids=block_ids,
            position_ids=all_position_ids[:, start:start + block_size],
            past_key_values=target_cache,
            use_cache=True,
            output_hidden_states=True,
            return_dict=True,
        )
        if atom_spec is None:
            posterior = _sample(
                verified.logits, temperature, ordinary_banned_ids
            )
        else:
            # Positions 0..B-2 predict atom payload/end slots. The final
            # posterior position is the post-atom ordinary bonus and must not
            # emit an orphan end token or <oof>.
            posterior = torch.cat(
                [
                    _sample(
                        verified.logits[:, :-1, :],
                        temperature,
                        (mask_token_id,),
                    ),
                    _sample(
                        verified.logits[:, -1:, :],
                        temperature,
                        ordinary_banned_ids,
                    ),
                ],
                dim=1,
            )
        verified_hidden = extract_context_feature(
            verified.hidden_states, draft_model.target_layer_ids
        )

        matches = block_ids[:, 1:] == posterior[:, :-1]
        prefix_match = int(matches.cumprod(dim=1).sum(dim=1)[0].item())

        if atom_spec is not None:
            valid_atom, invalid_reason = (
                validate_atomic_decoding_block(
                    block_ids[0].tolist(), physical_atom_config, count=atomic_count
                )
                if block_atomic_mode
                else validate_serialized_atom_tail(
                    anchor_id, block_ids[0, 1:].tolist(), physical_atom_config
                )
            )
            if valid_atom:
                # Physical atoms are committed without target agreement.
                output_ids[:, start:start + block_size] = block_ids
                full_target_hidden = torch.cat([full_target_hidden, verified_hidden], dim=1)
                bonus_position = start + block_size
                bonus_id = int(posterior[0, -1].item())
                bonus_spec = _atom_specs_by_start_id(physical_atom_config).get(
                    bonus_id
                )
                bonus_is_visible = bonus_position < max_length
                bonus_required = (
                    block_size
                    if bonus_spec is not None
                    and is_variable_trajectory_atom_name(bonus_spec.get("name", ""))
                    else int(bonus_spec["block_size"])
                    if bonus_spec is not None
                    else 0
                )
                if (
                    bonus_is_visible
                    and bonus_spec is not None
                    and max_length - bonus_position < bonus_required
                ):
                    # The committed atom itself is complete. Do not append a
                    # second atom trigger when the remaining user budget cannot
                    # hold that atom in full.
                    start += block_size - 1
                    acceptance_lengths.append(block_size)
                    break
                output_ids[:, bonus_position] = posterior[:, -1]
                start += block_size
                target_cache.crop(start)
                target_hidden = verified_hidden
                acceptance_lengths.append(block_size)
                continue

            # A schema-invalid proposal is regenerated whole by the target in
            # slot-constrained AR mode.
            atom_fallbacks += 1
            atom_fallback_reasons.append(invalid_reason)
            atom_fallback_details.append({
                "reason": invalid_reason,
                "proposed_token_ids": [
                    int(value) for value in block_ids[0].tolist()
                ],
                "guard": {},
                "fallback_strategy": "whole_atom",
                "retained_coordinate_count": 0,
                "ar_tail_forward_calls": block_size - 1,
            })
            target_cache.crop(start)
            draft_cache = DynamicCache()
            prior_tail: list[int] = []
            ar_hidden_parts = []
            current_id = output_ids[:, start:start + 1]
            atomic_descriptors = (
                _atomic_tail_descriptors(atomic_parts) if block_atomic_mode else None
            )
            for slot in range(block_size - 1):
                ar_output = target_language_model(
                    input_ids=current_id,
                    position_ids=all_position_ids[:, start + slot:start + slot + 1],
                    past_key_values=target_cache,
                    use_cache=True,
                    output_hidden_states=True,
                    return_dict=True,
                )
                ar_hidden_parts.append(extract_context_feature(
                    ar_output.hidden_states, draft_model.target_layer_ids
                ))
                next_id = (
                    _sample_atomic_tail_slot(
                        ar_output.logits[:, -1, :],
                        atomic_descriptors[slot],
                        prior_tail,
                        physical_atom_config,
                        temperature,
                    )
                    if block_atomic_mode
                    else _sample_atom_slot(
                        ar_output.logits[:, -1, :],
                        atom_spec,
                        slot,
                        prior_tail,
                        physical_atom_config,
                        temperature,
                    )
                ).reshape(1, 1)
                prior_tail.append(int(next_id.item()))
                output_ids[:, start + slot + 1] = next_id.reshape(1)
                current_id = next_id

            valid_atom, reason = (
                validate_atomic_decoding_block(
                    [anchor_id] + prior_tail,
                    physical_atom_config,
                    count=atomic_count,
                )
                if block_atomic_mode
                else validate_serialized_atom_tail(
                    anchor_id, prior_tail, physical_atom_config
                )
            )
            if not valid_atom:
                raise RuntimeError(f"Constrained target AR produced an invalid atom: {reason}")
            appended_hidden = torch.cat(ar_hidden_parts, dim=1)
            full_target_hidden = torch.cat([full_target_hidden, appended_hidden], dim=1)
            start += block_size - 1
            target_hidden = full_target_hidden
            acceptance_lengths.append(1)
            continue

        # Official DFlash ordinary-text acceptance: longest matching proposal
        # prefix followed by one target correction/bonus token.
        accepted_inputs = prefix_match + 1
        candidate = torch.cat(
            [
                block_ids[:, :accepted_inputs],
                posterior[:, prefix_match:prefix_match + 1],
            ],
            dim=1,
        )
        visible_candidate = candidate[:, :max_length - start]
        atom_offset, next_atom_spec = _first_atom_start_offset(
            visible_candidate, physical_atom_config
        )
        stop_offset = next(
            (
                offset
                for offset, token_id in enumerate(visible_candidate[0].tolist())
                if offset > 0 and int(token_id) in stop_ids
            ),
            None,
        )
        if stop_offset is not None and (
            atom_offset is None or stop_offset < atom_offset
        ):
            # Tokens after the first stop marker are not observable output and
            # therefore must not trigger atom routing or atom-budget errors.
            output_ids[:, start:start + stop_offset + 1] = (
                candidate[:, :stop_offset + 1]
            )
            start += stop_offset
            acceptance_lengths.append(stop_offset)
            break
        if atom_offset is not None:
            atom_start = start + atom_offset
            atom_budget = max_length - atom_start
            required = (
                parse_atomic_decoding_block_size(
                    output_ids[0, prompt_length:start].tolist()
                    + candidate[0, :atom_offset].tolist(),
                    atomic_decoding_tokenizer,
                )
                if is_variable_trajectory_atom_name(next_atom_spec.get("name", ""))
                else int(next_atom_spec["block_size"])
            )
            if atom_budget < required:
                if (
                    str(next_atom_spec.get("name")) == "bbox_2d"
                    and "objects_end_token_id" in physical_atom_config
                ):
                    # A hard generation limit can land inside the next B6 box.
                    # Keep every complete box already produced and terminate the
                    # objects list instead of raising or exposing a partial atom.
                    output_ids[:, start:atom_start] = candidate[:, :atom_offset]
                    output_ids[:, atom_start] = int(
                        physical_atom_config["objects_end_token_id"]
                    )
                    start = atom_start
                    acceptance_lengths.append(max(atom_offset - 1, 0))
                    break
                raise ValueError(
                    f"max_new_tokens truncates {next_atom_spec['name']} atom: need "
                    f"{required} tokens from its start, have {atom_budget}"
                )
            # Commit through the trigger, but do not commit or cache any atom
            # payload.  The next iteration sees the trigger as its anchor and
            # routes the entire tail through the type-specific block.
            output_ids[:, start:atom_start + 1] = candidate[:, :atom_offset + 1]
            accepted_hidden = verified_hidden[:, :atom_offset, :]
            full_target_hidden = torch.cat(
                [full_target_hidden, accepted_hidden], dim=1
            )
            start = atom_start
            target_cache.crop(start)
            target_hidden = accepted_hidden
            acceptance_lengths.append(atom_offset)
            continue

        output_ids[:, start:start + accepted_inputs + 1] = candidate
        accepted_hidden = verified_hidden[:, :accepted_inputs, :]
        full_target_hidden = torch.cat([full_target_hidden, accepted_hidden], dim=1)
        start += accepted_inputs
        target_cache.crop(start)
        target_hidden = accepted_hidden
        acceptance_lengths.append(accepted_inputs)

    result = output_ids[:, prompt_length:min(start + 1, max_length)]
    if stop_ids and result.numel():
        stop_positions = torch.tensor(
            [i for i, token_id in enumerate(result[0].tolist()) if token_id in stop_ids],
            device=device,
        )
        if stop_positions.numel():
            result = result[:, :int(stop_positions[0].item()) + 1]
    publication_error = None
    try:
        atomic_blocks_published = validate_publication(
            result[0].tolist() if result.numel() else [],
            physical_atom_config,
            atomic_decoding_tokenizer,
        )
    except (RuntimeError, ValueError) as error:
        if publication_errors == "raise":
            raise
        # Keep the rejected output for evaluation protocols that score it.
        atomic_blocks_published = 0
        publication_error = str(error)

    if not return_stats:
        return result
    if device.type == "cuda":
        torch.cuda.synchronize(device)
    decode_time = time.perf_counter() - decode_started
    num_output_tokens = result.shape[1]
    stats = SimpleNamespace(
        output_ids=result,
        num_input_tokens=prompt_length,
        num_output_tokens=num_output_tokens,
        time_to_first_token=time_to_first_token,
        time_per_output_token=decode_time / max(num_output_tokens, 1),
        acceptance_lengths=acceptance_lengths,
        atom_fallbacks=atom_fallbacks,
        atom_fallback_reasons=atom_fallback_reasons,
        atom_fallback_details=atom_fallback_details,
        drive_oof_pair_repairs=0,
        atomic_blocks_published=atomic_blocks_published,
        draft_temperature=draft_temperature,
        verify_atoms=bool(verify_atoms),
        text_block_size=int(text_block_size),
    )
    if publication_error is not None:
        stats.publication_error = publication_error
    return stats
