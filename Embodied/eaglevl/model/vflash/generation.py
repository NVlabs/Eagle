"""VFlash speculative decoding with physical-atom block routing.

The ordinary-text path follows the official DFlash longest-prefix verifier on
16-token blocks.  A physical atom is proposed whole in one draft forward under
slot-level token masks and committed without target agreement; the target then
forwards the committed block for its KV cache and the following token.  Point
and box atoms have fixed lengths, while trajectory atoms take their block size
from the latest ``atomic_decoding`` tool call.  An atom that fails its schema
is regenerated by the frozen target in constrained AR mode and is never
partially published.
"""

